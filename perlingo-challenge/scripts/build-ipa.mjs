import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const root=new URL('../',import.meta.url);
const {entries}=JSON.parse(readFileSync(new URL('data/word-bank/ipa-guides.json',root),'utf8'));
const data={};
for(const entry of entries){
 const key=`${entry.pack}:${entry.language}`;
 if(data[key])throw Error(`Duplicate IPA guide: ${key}`);
 if(!entry.word||!entry.ipa||/[\[\]\/<>]/u.test(entry.ipa))throw Error(`Invalid IPA guide: ${key}`);
 data[key]={word:entry.word,ipa:entry.ipa,...(entry.evidence?{source:entry.evidence.url}: {})};
}
const output='// Generated by scripts/build-ipa.mjs; edit data/word-bank/ipa-guides.json.\n// Dictionary selections: Wiktionary contributors, CC BY-SA 4.0; https://creativecommons.org/licenses/by-sa/4.0/; source URLs below, full evidence in the ledger.\nexport const ipaGuides='+JSON.stringify(data,null,2)+';\n';
const target=new URL('public/ipa-data.js',root);
if(process.argv.includes('--check')){
 if(readFileSync(target,'utf8')!==output)throw Error('IPA output is stale; run node perlingo-challenge/scripts/build-ipa.mjs');
}else writeFileSync(target,output);
console.log(`${entries.length} IPA guides ${process.argv.includes('--check')?'checked':'written'}: ${fileURLToPath(target)}`);
