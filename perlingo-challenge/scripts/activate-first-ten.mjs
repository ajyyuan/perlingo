import {audioException} from './audio-exceptions.mjs';
// Publish into the local app only after every entry has source evidence and screened audio.
// This does not commit, push, schedule, or deploy anything.
import {readFile,writeFile,mkdir,rename} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {firstTen} from '../data/word-bank/first-ten.js';
const root=new URL('../',import.meta.url);
const read=async file=>JSON.parse(await readFile(new URL(file,root),'utf8'));
const evidence=await read('data/word-bank/first-ten-checks.json');
const sources=await read('generated-audio-sources.json');
const checks=await read('generated-audio-checks.json');
const failures=[],ready=[];
for(const pack of firstTen){
 const before=failures.length;
for(const entry of pack.entries){
 const key=pack.id+':'+entry.id;
 const proof=evidence.entries.find(e=>e.pack===pack.id&&e.language===entry.id);
 if(!proof?.sourceRevision||proof.word!==entry.word||JSON.stringify(proof.accepted)!==JSON.stringify(entry.accepted))failures.push(key+' source evidence');
 const source=sources.find(s=>s.pack===pack.id&&s.language===entry.id&&s.word===entry.word);
 if(!source){failures.push(key+' missing audio');continue;}
 const hash=createHash('sha256').update(await readFile(new URL(source.stagedFile||('public'+source.file),root))).digest('hex');
 if(hash!==source.sha256)failures.push(key+' audio hash');
 if(!audioException(source)&&!checks.rows.some(c=>c.sha256===hash&&c.pack===pack.id&&c.language===entry.id&&c.word===entry.word&&c.provider==='soniox'&&JSON.stringify(c.orthographicAlternatives||[])===JSON.stringify(entry.orthographicAlternatives||[])&&JSON.stringify(c.transcriptAlternatives||[])===JSON.stringify(entry.transcriptAlternatives||[])&&c.exactMatch&&!c.error))failures.push(key+' independent word screen');
}
if(failures.length===before)ready.push(pack);
}
if(failures.length&&!process.argv.includes('--ready'))throw Error('Not activated: '+failures.join(', '));

for(const source of sources.filter(s=>s.stagedFile&&ready.some(p=>p.id===s.pack))){await mkdir(new URL('public/audio/generated/',root),{recursive:true});await rename(new URL(source.stagedFile,root),new URL('public'+source.file,root));delete source.stagedFile;}
await writeFile(new URL('generated-audio-sources.json',root),JSON.stringify(sources,null,2)+'\n');
await writeFile(new URL('public/noun-packs.js',root),'// Generated by scripts/activate-first-ten.mjs. Source evidence: data/word-bank/first-ten-checks.json\nexport const nounPacks='+JSON.stringify(ready,null,2)+';\n');
console.log(`Activated ${ready.length} complete packs / ${ready.length*50} entries. Staged failures: ${failures.join(', ')||'none'}`);
