"""Offline generation. Requires espeakng-loader==0.2.4; never used by the browser."""
import ctypes as C
import json, subprocess
from pathlib import Path
import espeakng_loader as loader
root=Path(__file__).resolve().parent.parent
inputs=json.loads(subprocess.check_output(['node',str(root/'scripts/ipa-inputs.mjs')]))
lib=loader.load_library()
lib.espeak_Initialize.argtypes=[C.c_int,C.c_int,C.c_char_p,C.c_int]
assert lib.espeak_Initialize(2,0,loader.get_data_path().encode(),0)>0
lib.espeak_SetVoiceByName.argtypes=[C.c_char_p]
lib.espeak_TextToPhonemes.argtypes=[C.POINTER(C.c_char_p),C.c_int,C.c_int]
lib.espeak_TextToPhonemes.restype=C.c_char_p
lib.espeak_Info.restype=C.c_char_p
version=lib.espeak_Info(None).decode()
result={}
for lang,texts in inputs.items():
 assert lib.espeak_SetVoiceByName(lang.encode())==0
 result[lang]={}
 for text in texts:
  pointer=C.c_char_p(text.replace('’',"'").encode('utf-8'))
  pieces=[]
  while pointer.value:
   phonemes=lib.espeak_TextToPhonemes(C.byref(pointer),1,2)
   if phonemes:pieces.append(phonemes.decode())
  ipa=' '.join(' '.join(pieces).replace('_',' ').split())
  if not ipa:raise ValueError((lang,text))
  # Language-switch markers indicate a foreign fallback; do not teach it as IPA.
  result[lang][text]=None if '(' in ipa or ')' in ipa else ipa.replace('-', '')
 print(lang,len(texts))
output=root/'src/content/ipa-data.js'
output.write_text('// Generated by scripts/generate-ipa.py; approximate, not independently reviewed.\n'
 + 'export const ipaSource='+json.dumps({'engine':'eSpeak NG','version':version,'loader':'0.2.4','voices':{'es':'es','fr':'fr','de':'de'}},ensure_ascii=False)+';\n'
 + 'export const ipaData='+json.dumps(result,ensure_ascii=False,indent=2)+';\n')
