import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {combineNotes} from '../lemmas/notes-library.js';
const read=p=>JSON.parse(readFileSync(new URL('../'+p,import.meta.url),'utf8'));
const review=read('data/spanish-lemmas/choice-review.json');
const library=combineNotes(read('lemmas/data/notes.json'),read('lemmas/data/context.json'),read('lemmas/data/day1-usage.json'));
const notes=new Map(library.notes.map(n=>[n.id,n]));
const deck=read('lemmas/data/deck.json').map(c=>({...c,meaning:notes.get(c.id).meaning}));
const cards=new Map(deck.map(c=>[c.id,c]));
assert.equal(review.version,1);
assert.deepEqual(review.entries.map(r=>r.id),deck.map(c=>c.id),'Review must cover the complete ordered deck');
const options={};
for(const row of review.entries){
 const card=cards.get(row.id);
 assert.equal(row.rank,card.rank);assert.equal(row.lemma,card.lemma);
 assert.equal(row.meaning,card.meaning,'Stale correct meaning: '+row.id);
 assert.equal(row.distractors.length,3,row.id);
 assert.equal(new Set([row.id,...row.distractors.map(d=>d.id)]).size,4,row.id);
 for(const d of row.distractors){
  const source=cards.get(d.id);assert.ok(source,'Unknown distractor: '+d.id);
  assert.equal(d.lemma,source.lemma);assert.equal(d.meaning,source.meaning,'Re-review changed distractor: '+row.id+' / '+d.id);
 }
 const values=[row.meaning,...row.distractors.map(d=>d.meaning)];
 assert.equal(new Set(values.map(s=>s.normalize('NFC').trim().toLowerCase())).size,4,row.id);
 options[row.id]=values;
}
const output='// Generated by scripts/build-lemma-choices.mjs from reviewed question sets.\nexport const choiceOptions={\n'+Object.entries(options).map(([id,values])=>' '+JSON.stringify(id)+':'+JSON.stringify(values)).join(',\n')+'\n};\n';
const destination=new URL('../lemmas/choice-data.js',import.meta.url);
if(process.argv.includes('--check'))assert.equal(readFileSync(destination,'utf8'),output,'choice-data.js is stale');
else writeFileSync(destination,output);
console.log(`${review.entries.length} reviewed MCQs; ${review.entries.length*3} distractors; no unrestricted fallback`);
