"""Compile frozen, tense/person-tagged evidence; no conjugation guessing or network."""
import json, pathlib
ROOT=pathlib.Path(__file__).resolve().parents[1]
D=ROOT/'data/spanish-lemmas'
read=lambda p:json.loads(p.read_text())
verbs=[c for c in read(ROOT/'lemmas/data/deck.json') if c['sourceTag']=='V']
slots=[('first-person','singular'),('second-person','singular'),('third-person','singular'),('first-person','plural'),('second-person','plural'),('third-person','plural')]
groups={'present':['indicative','present'],'preterite':['indicative','preterite'],'imperfect':['indicative','imperfect'],'future':['indicative','future'],'conditional':['conditional'],'subjunctive':['subjunctive','present'],'commands':['imperative'],'negative':['imperative','negative']}
snapshot=read(D/'conjugation-evidence.json')
assert snapshot.get('dumpDate') and snapshot.get('extractionDate'), 'Verify and record source snapshot dates before building.'
evidence=snapshot['records']
result={}; failures=[]
for card in verbs:
 w=card['lemma']
 if w not in evidence:failures.append(w+': missing evidence');continue
 raw=evidence[w];forms=[]
 for entry in raw['entries']:
  active=False
  for f in entry['forms']:
   tags=set(f['tags'])
   if f.get('source')!='conjugation':continue
   if 'inflection-template' in tags:active=False
   if 'infinitive' in tags:active=f['form']==w
   if active and not tags&{'combined-form','vos-form','archaic','obsolete','dated','rare','nonstandard'}:forms.append(f)
 def select(tags,negative=False):
  return list(dict.fromkeys(f['form'] for f in forms if set(tags)<=set(f['tags']) and ('negative' in f['tags'])==negative and f['form'] not in ['-','—','–']))
 out={}
 for key,tags in groups.items():
  selected=[1,2,4,5] if key in ['commands','negative'] else range(6)
  out[key]=[select(tags+list(slots[i]),key=='negative') for i in selected]
  if key=='negative':out[key]=[[('no '+f) for f in row] for row in out[key]]
  if any(not row for row in out[key]):failures.append(f'{w}: {key} empty slots {out[key]}')
 out['participle']=select(['masculine','singular','past','participle'])
 if not out['participle']:failures.append(w+': missing participle')
 if w in {'escribir','pagar','elegir'}:
  preferred={'escribir':'escrito','pagar':'pagado','elegir':'elegido'}[w]
  assert preferred in out['participle']
  out['participle']=[preferred]
 out['perfect']=[[a+' '+p for p in out['participle']] for a in ['he','has','ha','hemos','habéis','han']]
 result[card['id']]=out
if failures:print('\n'.join(failures));raise SystemExit(1)
(ROOT/'lemmas/verb-forms-data.js').write_text('// Generated by scripts/build-lemma-conjugations.py from frozen tagged Wiktionary evidence.\nexport const verbForms = '+json.dumps(result,ensure_ascii=False,separators=(',',':'))+';\n')
print(f'Built {len(result)} verb paradigms.')
