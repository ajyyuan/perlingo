import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const read=p=>JSON.parse(readFileSync(new URL('../'+p,import.meta.url)));
const deck=read('lemmas/data/deck.json');
const review=read('data/spanish-lemmas/later-day-recall-review.json');
const {groups}=read('data/spanish-lemmas/later-day-usage.json');
const evidence=read('data/spanish-lemmas/later-day-source-evidence.json');
assert.deepEqual(review.entries.map(e=>e.id),deck.slice(250).map(c=>c.id));
const ids=new Set(deck.slice(250).map(c=>c.id));
const policies={},meanings={};
for(const entry of review.entries){
 if(entry.teachingMeaning)meanings[entry.id]=entry.teachingMeaning;
 if(!entry.policy)continue;
 const p=entry.policy;
 assert.ok(p.prompt&&p.cue&&typeof p.note==='string',entry.id);
 assert.equal(new Set(p.alternatives).size,p.alternatives.length,entry.id);
 for(const a of p.alternatives){assert.match(a,/^\p{L}+$/u);assert.ok(evidence.sources[a],entry.id+': '+a);assert.notEqual(a,entry.lemma);}
 policies[entry.id]=p;
}
assert.equal(new Set(groups.map(g=>g.id)).size,groups.length);
for(const g of groups){
 assert.ok(g.members.length&&g.sections.length,g.id);
 for(const id of g.members)assert.ok(ids.has(id),id);
 for(const s of g.sections){assert.ok(s.text&&s.title&&s.sources.length,g.id);for(const [label,url]of s.sources)assert.ok(label&&new URL(url).protocol==='https:');}
}
for(const entry of review.entries)assert.deepEqual(entry.comparisonGroups,groups.filter(g=>g.members.includes(entry.id)).map(g=>g.id));
for(const [file,name,value]of [['later-recall-data.js','laterRecall',policies],['later-usage-data.js','laterUsage',groups],['later-teaching-data.js','laterMeanings',meanings]]){
 const text='// Generated by scripts/build-later-recall.mjs; edit the review/usage JSON sources.\nexport const '+name+'='+JSON.stringify(value,null,2)+';\n';
 const path=new URL('../lemmas/'+file,import.meta.url);
 if(process.argv.includes('--check'))assert.equal(readFileSync(path,'utf8'),text,file+' is stale');else writeFileSync(path,text);
}
console.log(`${review.entries.length} screened cards; ${Object.keys(policies).length} policies; ${groups.length} comparison topics`);
