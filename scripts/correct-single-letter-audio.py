"""Generate bounded, immutable Spanish y corrections. Existing Speech key on stdin.
No upload or original-manifest mutation. Completed requests resume; ambiguous ones stop.
"""
import pathlib,json,sys,hashlib,urllib.request,urllib.error
R=pathlib.Path(__file__).resolve().parents[1];folder=R/'lemmas/audio-corrections';folder.mkdir(exist_ok=True)
ledgerPath=R/'data/spanish-lemmas/audio/single-letter-corrections.json'
ledger=json.loads(ledgerPath.read_text()) if ledgerPath.exists() else {'format':'audio-24khz-48kbitrate-mono-mp3','clips':[]}
key=sys.stdin.read().strip();assert len(key)>30,'Missing Speech key'
def save():ledgerPath.write_text(json.dumps(ledger,ensure_ascii=False,indent=2)+'\n')
for gender,name in [('masculine','manifest.json'),('feminine','manifest-feminine.json')]:
 m=json.loads((R/'src/audio/azure'/name).read_text())
 for locale,voice in m['regions'].items():
  if not locale.startswith('es-'):continue
  for text,ipa in [('y','i')]:
   ssml=f'<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" xml:lang="{locale}"><voice name="{voice}"><phoneme alphabet="ipa" ph="{ipa}">{text}</phoneme></voice></speak>'
   ident=hashlib.sha256(ssml.encode()).hexdigest()[:24];file=folder/(ident+'.mp3')
   previous=next((r for r in ledger['clips'] if r['id']==ident),None)
   if previous:
    assert previous['status']=='complete' and file.exists() and hashlib.sha256(file.read_bytes()).hexdigest()==previous['sha256'],'Unresolved attempt; inspect before retrying'
    continue
   record=dict(id=ident,locale=locale,voice=voice,gender=gender,text=text,ipa=ipa,ssml=ssml,status='attempted',disposition='active',file=file.name)
   ledger['clips'].append(record);save()
   req=urllib.request.Request('https://eastus.tts.speech.microsoft.com/cognitiveservices/v1',data=ssml.encode(),headers={'Ocp-Apim-Subscription-Key':key,'Content-Type':'application/ssml+xml','X-Microsoft-OutputFormat':ledger['format']})
   try:
    with urllib.request.urlopen(req,timeout=45) as response:raw=response.read()
   except urllib.error.HTTPError as e:raise RuntimeError('Speech HTTP '+str(e.code)+'; request retained, no automatic retry') from None
   assert len(raw)>100;file.write_bytes(raw);record.update(status='complete',bytes=len(raw),sha256=hashlib.sha256(raw).hexdigest());save()
  print(locale,gender,'y correction complete',flush=True)
assert len([r for r in ledger['clips'] if r['text']=='y'])==8
mapping={}
for r in ledger['clips']:
 if r['text']!='y':continue
 mapping.setdefault(r['gender'],{}).setdefault(r['locale'],{})[r['text']]='/lemmas/audio-corrections/'+r['file']
(R/'lemmas/single-letter-audio.js').write_text('// Generated by scripts/correct-single-letter-audio.py; same-origin corrections.\nexport const singleLetterAudio='+json.dumps(mapping,indent=2)+';\n')
